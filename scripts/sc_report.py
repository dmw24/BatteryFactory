#!/usr/bin/env python3
"""Supply-chain coverage report -> team/RECONCILIATION_SC.md (regenerated; hand-written notes go below the marker)."""
import os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "team/RECONCILIATION_SC.md")
MARK = "<!-- hand-written notes below this line are kept on regeneration -->"


def fmt(v):
    return "–" if pd.isna(v) or v == 0 else f"{v:,.0f}"


def main():
    a = pd.read_csv(os.path.join(ROOT, "sc_assets.csv"))
    b = pd.read_csv(os.path.join(ROOT, "sc_benchmark.csv"))
    L = ["# Supply-chain reconciliation (generated by scripts/sc_report.py)", "",
         f"Assets: {len(a)} — by step and status (never summed across statuses):", "",
         "| step | operational | under construction | announced | paused/cancelled |", "|---|---:|---:|---:|---:|"]
    for st, g in a.groupby("step"):
        act = g[g.project_state.fillna("active") == "active"]
        L.append(f"| {st} | {(act.status=='operational').sum()} | {(act.status=='under_construction').sum()} | "
                 f"{(act.status=='announced').sum()} | {(g.project_state.fillna('active')!='active').sum()} |")
    L += ["", "Evidence: " + f"{(a.evidence_tier=='confirmed').sum()} rows confirmed, {(a.evidence_tier=='reported').sum()} reported-tier; "
          f"{a.latitude.notna().sum()} with coordinates; mean confidence {a.confidence.mean():.2f}.", "",
          "## Mining — 2025 production vs USGS MCS 2026 (operational assets; company-level output not tied to a site shown separately)", "",
          "| commodity | country | USGS | ours (sites) | company-level extra | coverage |", "|---|---|---:|---:|---:|---:|"]
    m = b[(b.step == "mining") & (b.year == 2025) & (b.metric == "production") & b.source.str.startswith("USGS")]
    for r in m.sort_values(["commodity", "benchmark"], ascending=[True, False]).itertuples():
        if r.country != "World" and r.benchmark < 0.02 * m[(m.commodity == r.commodity) & (m.country == "World")].benchmark.max():
            continue
        extra = r.unallocated_production if r.country == "World" else 0
        cov = (r.ours_production + extra) / r.benchmark
        L.append(f"| {r.commodity} | {r.country} | {fmt(r.benchmark)} {r.unit} | {fmt(r.ours_production)} | {fmt(extra)} | {cov:.0%} |")
    L += ["", "## Processing — China/world output benchmarks vs our capacity and company-disclosed output", "",
          "| step | product | metric | area | year | benchmark | built site capacity (installed/dated) | rest of operational plans (upper bound) | unallocated company capacity | company output (China-only cos.) | company output incl. overseas |",
          "|---|---|---|---|---|---:|---:|---:|---:|---:|---:|"]
    p = b[(b.step != "mining") & b.year.between(2024, 2025)]
    p = p.sort_values("year").groupby(["step", "commodity", "metric", "country"]).tail(1)
    for r in p.itertuples():
        L.append(f"| {r.step} | {r.commodity} | {r.metric} | {r.country} | {r.year} | {fmt(r.benchmark)} {r.unit} | {fmt(r.ours_capacity)} | "
                 f"{fmt(r.plan_only_capacity)} | {fmt(r.unallocated_capacity)} | {fmt(r.company_disclosed_output)} | {fmt(r.company_disclosed_output_incl_overseas)} |")
    ni = b[(b.commodity.str.startswith("nickel")) & (b.step == "refining") & (b.year == 2025)]
    if len(ni):
        r = ni.iloc[0]
        L += ["", f"Nickel: INSG primary nickel {fmt(r.benchmark)} t Ni vs our built final-product capacity {fmt(r.ours_capacity)} "
              f"(NPI/FeNi/refined/sulphate); intermediates (MHP, matte) {fmt(r.intermediate_capacity)} t Ni shown separately, not added."]
    L += ["", "Notes: benchmarks are comparison only (USGS public domain; MIIT official; industry figures via open press — "
          "see data/supply_chain/benchmarks/aggregates.csv for quotes and URLs). Capacity ≥ output is expected; company-disclosed "
          "output is the share of the benchmark produced by companies whose filings we read.", "", MARK]
    keep = ""
    if os.path.exists(OUT):
        t = open(OUT).read()
        if MARK in t:
            keep = t.split(MARK, 1)[1]
    open(OUT, "w").write("\n".join(L) + keep)
    print("\n".join(L[:12]))


if __name__ == "__main__":
    main()
