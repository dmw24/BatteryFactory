#!/usr/bin/env python3
"""Regenerate the figures block of team/FINAL_REPORT_SC.md from current outputs (audit 4: report must match outputs)."""
import os
import pandas as pd
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
a = pd.read_csv(os.path.join(ROOT, "sc_assets.csv"))
ev = pd.read_csv(os.path.join(ROOT, "data/supply_chain/field_evidence.csv"))
ct = pd.read_csv(os.path.join(ROOT, "data/supply_chain/company_totals.csv"))
b = pd.read_csv(os.path.join(ROOT, "sc_benchmark.csv"))
act = a[a.project_state.fillna("active") == "active"]
steps = ", ".join(f"{k} {v}" for k, v in a.groupby("step").size().items())
links = a.feeds.dropna().map(lambda s: [x.strip() for x in s.split(",") if x.strip()])
n_links = sum(len(x) for x in links); n_cell = sum(1 for x in links for y in x if y.startswith("cell:"))
def cov(step, com, met, ctry):
    s = b[(b.step == step) & (b.commodity == com) & (b.metric == met) & (b.country == ctry)]
    if step == "mining":
        s = s[s.source.str.startswith("USGS")]
    if not len(s):
        return "n/a"
    r = s.sort_values("year").iloc[-1]
    return f"{(r.ours_production if step == 'mining' else r.ours_capacity) / r.benchmark:.0%}"
block = f"""<!-- generated by scripts/sc_status.py -->
- **{len(a)} assets** ({len(act)} active): {steps}.
- **{len(ev)} evidence links**; {(a.evidence_tier == 'confirmed').sum()} rows confirmed tier, {(a.evidence_tier == 'reported').sum()} reported-tier (≤0.5 confidence).
- {a.latitude.notna().sum()} assets with coordinates; {links.size} assets with plant-level supply links ({n_links} links, {n_cell} into cell plants);
  {a.feeds_company.notna().sum()} assets with company-level links (feeds_company); {len(ct)} company-level disclosures.
- Coverage (sourced at asset level): lithium mine output {cov('mining','lithium','production','World')} of USGS world 2025;
  cobalt mine output {cov('mining','cobalt','production','World')} (plus company-level CMOC); nickel mines Canada {cov('mining','nickel','production','Canada')};
  China lithium chemicals dated-built capacity vs 2025 output {cov('refining','lithium','production','China')}; China cathode dated-built capacity vs output (company-disclosed output covers ~50%) {cov('cathode','cathode','production','China')}.
<!-- end generated -->"""
p = os.path.join(ROOT, "team/FINAL_REPORT_SC.md")
t = open(p).read()
if "<!-- generated by scripts/sc_status.py -->" in t:
    pre, rest = t.split("<!-- generated by scripts/sc_status.py -->", 1)
    post = rest.split("<!-- end generated -->", 1)[1]
    t = pre + block + post
else:
    t = t.replace("## What exists\n", "## What exists\n" + block + "\n", 1)
open(p, "w").write(t)
print(block)
